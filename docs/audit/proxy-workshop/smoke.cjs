// Usage: PLAYWRIGHT_MODULE=<installed playwright directory> node smoke.cjs
// BASE_URL defaults to the local development server. Uses its own browser context.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const base = process.env.BASE_URL || 'http://127.0.0.1:3227'
const out = path.join(__dirname, 'evidence')

;(async () => {
  await fs.mkdir(out, { recursive: true })
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(`${base}/proxies`)
    await page.getByText(/Draft saved in this browser/).waitFor()
    assert.equal(await page.locator('meta[name=robots]').getAttribute('content'), 'noindex, nofollow')
    assert.equal(await page.locator('nav[aria-label="Main navigation"] a[href="/proxies"]').count(), 0)
    await page.screenshot({ path: path.join(out, 'desktop.jpg'), quality: 75 })
    await page.getByRole('button', { name: 'Try a sample' }).click()
    await page.getByRole('button', { name: 'Check names & double faces' }).click()
    await page.getByRole('button', { name: 'Check card names again' }).waitFor({ timeout: 45000 })
    assert.match(await page.locator('#deck').innerText(), /2 double-faced copies found/)
    assert.doesNotMatch(await page.locator('#deck').innerText(), /Not found/)
    await page.getByLabel('Double-faced cards').selectOption('separate')
    assert.match(await page.locator('#printers').innerText(), /39 physical cards/)
    await page.getByLabel('Include sideboard').check()
    assert.match(await page.locator('#printers').innerText(), /40 physical cards/)
    await page.getByLabel('Print basic lands').uncheck()
    assert.match(await page.locator('#printers').innerText(), /16 physical cards/)
    await page.getByLabel('Deck copies').selectOption('2')
    assert.match(await page.locator('#printers').innerText(), /32 physical cards/)
    const csvPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: /Front \/ back checklist/ }).click()
    const csv = await csvPromise
    await csv.saveAs(path.join(out, 'manifest.csv'))
    const csvText = await fs.readFile(path.join(out, 'manifest.csv'), 'utf8')
    assert.match(csvText, /"2","Bala Ged Sanctuary","Obsidian"/)
    assert.match(csvText, /"2","Fire \/\/ Ice","Obsidian"/)
    const pngPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Download back PNG ↓', exact: true }).click()
    const png = await pngPromise
    await png.saveAs(path.join(out, 'back.png'))
    const pngBytes = await fs.readFile(path.join(out, 'back.png'))
    assert.equal(pngBytes.readUInt32BE(16), 1500)
    assert.equal(pngBytes.readUInt32BE(20), 2100)
    await page.locator('input[type=file][accept="image/png,image/jpeg"]').setInputFiles(path.join(out, 'back.png'))
    await page.getByText('1500 × 2100 px · original file', { exact: true }).waitFor()
    assert.match(await page.locator('#backs').innerText(), /1500 × 2100 px · original file/)
    await page.locator('input[type=file][accept=".txt,.dec,.dek,text/plain"]').setInputFiles({ name: 'deck.txt', mimeType: 'text/plain', buffer: Buffer.from('100 Forest') })
    await page.waitForFunction(() => document.querySelector('#deck-list').value === '100 Forest')
    await page.getByLabel('Print basic lands').check()
    await page.getByLabel('Deck copies').selectOption('1')
    assert.match(await page.locator('#printers').innerText(), /\$55\.00/)
    const txtPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: /Download deck list/ }).click()
    const txt = await txtPromise
    assert.equal((await fs.readFile(await txt.path(), 'utf8')).trim(), '100 Forest')
    await page.getByLabel('Shipping (USD)', { exact: true }).fill('8.50')
    await page.getByLabel('Tax / import fees (USD)', { exact: true }).fill('0')
    assert.match(await page.locator('#printers').innerText(), /\$63\.50/)
    await page.getByLabel('Deck copies').selectOption('2')
    assert.equal(await page.getByLabel('Shipping (USD)', { exact: true }).inputValue(), '')
    assert.match(await page.locator('#printers').innerText(), /\$90\.00/)
    await page.getByLabel('Finished images → custom deck').check()
    await page.getByLabel('Printing quote (USD)', { exact: true }).fill('60')
    await page.getByLabel('Shipping (USD)', { exact: true }).fill('10')
    await page.getByLabel('Tax / import fees (USD)', { exact: true }).fill('5')
    assert.match(await page.locator('#printers').innerText(), /\$75\.00/)
    const planPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: /Save complete setup plan/ }).click()
    const plan = await planPromise
    await plan.saveAs(path.join(out, 'plan.json'))
    assert.equal(JSON.parse(await fs.readFile(path.join(out, 'plan.json'), 'utf8')).destination, 'United States')
    await page.waitForTimeout(550)
    await page.reload()
    await page.getByText(/Draft saved in this browser/).waitFor()
    assert.equal(await page.getByLabel('Deck list', { exact: true }).inputValue(), '100 Forest')
    assert.equal(await page.getByLabel('Deck copies').inputValue(), '2')
    assert.equal(await page.getByLabel('Shipping (USD)', { exact: true }).inputValue(), '')
    await page.getByLabel('Deck list', { exact: true }).fill('0 Sol Ring\n1 Forest')
    assert.match(await page.locator('#deck').innerText(), /Line 1:/)
    assert.equal(await page.getByRole('button', { name: /Download deck list/ }).isDisabled(), true)
    await page.getByLabel('Deck list', { exact: true }).fill('1 Sol Ring')
    await page.route('https://api.scryfall.com/cards/collection', route => route.abort())
    await page.getByRole('button', { name: 'Check names & double faces' }).click()
    await page.getByRole('alert').filter({ hasText: 'Could not reach Scryfall' }).waitFor()
    assert.equal(await page.getByLabel('Deck list', { exact: true }).inputValue(), '1 Sol Ring')
    await page.unroute('https://api.scryfall.com/cards/collection')
    await page.getByRole('button', { name: 'Dismiss error' }).click()
    await page.getByRole('button', { name: 'Check names & double faces' }).click()
    await page.getByRole('button', { name: 'Check card names again' }).waitFor({ timeout: 45000 })
    await page.waitForTimeout(8200)
    for (const width of [390, 320]) {
      await page.setViewportSize({ width, height: 844 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${width}px overflow`)
      await page.evaluate(() => scrollTo(0, 0))
      await page.screenshot({ path: path.join(out, `mobile-${width}.jpg`), fullPage: true, quality: 75 })
    }
    await page.evaluate(() => { document.documentElement.classList.remove('dark'); document.documentElement.classList.add('light') })
    await page.screenshot({ path: path.join(out, 'mobile-light.jpg'), fullPage: true, quality: 75 })
    assert.deepEqual(errors, [], 'No page runtime errors')
    await fs.writeFile(path.join(out, 'result.json'), JSON.stringify({ base, checkedAt: new Date().toISOString(), passed: true, errors, checks: ['live Scryfall names and split/DFC', 'face count / sideboard / basics / copies', 'CSV / PNG / JSON downloads', 'US / USD prices and manual quotes', 'stale quote reset', 'local draft recovery', 'invalid rows block export', 'network failure and recovery', '320/390px overflow', 'noindex and no navigation link'] }, null, 2))
    console.log('Proxy Workshop browser checks passed.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
